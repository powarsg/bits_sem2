# The six legal neighbours of a cell (dr, dc) - see adjacency rules above.
NEIGHBOUR_OFFSETS = ((-1, 0), (1, 0), (0, -1), (0, 1), (-1, 1), (1, -1))

# UCT exploration constant.  c = sqrt(2) is the theoretical value for rewards
# normalised to [0, 1], which is exactly our win / loss reward scheme.
EXPLORATION_CONSTANT = math.sqrt(2)

SEPARATOR = "=" * 78


