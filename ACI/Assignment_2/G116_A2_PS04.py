def build_arg_parser():
    parser = argparse.ArgumentParser(
        description="Hex game AI (Monte Carlo Tree Search / UCT) - Group G116")
    parser.add_argument("--input", default=DEFAULT_INPUT_FILE,
                        help="input file (default: %s)" % DEFAULT_INPUT_FILE)
    parser.add_argument("--output", default=DEFAULT_OUTPUT_FILE,
                        help="output file (default: %s)" % DEFAULT_OUTPUT_FILE)
    parser.add_argument("--test", action="store_true",
                        help="run the built-in test cases instead of a game")
    parser.add_argument("--append", action="store_true",
                        help="append to the output file instead of overwriting")
    parser.add_argument("--seed", type=int, default=None,
                        help="seed of the rollout RNG (reproducible games)")
    return parser


def main(argv=None):
    args = build_arg_parser().parse_args(argv)
    logger = None
    try:
        logger = OutputLogger(args.output, "a" if args.append else "w")
        if args.test:
            return 0 if run_test_cases(logger) else 1

        try:
            size, time_limit, cells = load_game_input(args.input)
            logger.write("Input file read successfully : %s" % args.input)
        except InvalidBoardError as exc:
            logger.write("INPUT ERROR : %s" % exc)
            logger.write("Falling back to manual setup.")
            size, time_limit, cells = prompt_for_setup()

        game = HexGame(size, time_limit, cells, logger, seed=args.seed)
        game.run()
        logger.write("")
        logger.write("Complete transcript written to '%s'." % args.output)
        return 0
    except KeyboardInterrupt:
        if logger:
            logger.write("")
            logger.write("Interrupted by the user - the program stops cleanly.")
        return 1
    except HexError as exc:
        message = "FATAL ERROR : %s" % exc
        if logger:
            logger.write(message)
        else:
            print(message, file=sys.stderr)
        return 1
    finally:
        if logger:
            logger.close()


if __name__ == "__main__":
    sys.exit(main())
