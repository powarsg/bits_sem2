class OutputLogger:
    """Writes every line simultaneously to the console and to outputPS04.txt."""

    def __init__(self, path, mode="w"):
        self.path = path
        try:
            self.handle = open(path, mode, encoding="utf-8")
        except OSError as exc:
            raise HexError("Cannot open output file '%s' : %s" % (path, exc))

    def write(self, text=""):
        print(text)
        self.handle.write(text + "\n")
        self.handle.flush()

    def write_prompt(self, text):
        """Show a prompt on the console and mirror it into the output file."""
        self.handle.write(text + "\n")
        self.handle.flush()

    def close(self):
        try:
            self.handle.close()
        except OSError:
            pass


def format_int(value):
    return "{:,}".format(int(value))


def parse_move(text, size):
    """
    Convert a user string such as '4,1' / '4 1' / '(4, 1)' into (row, col).
    Raises InvalidMoveError with a descriptive message for every bad input.
    """
    if text is None:
        raise InvalidMoveError("No input received.")
    tokens = [t for t in re.split(r"[\s,;()\[\]]+", text.strip()) if t]
    if len(tokens) != 2:
        raise InvalidMoveError(
            "Expected exactly two numbers in the form 'row,col' "
            "(received: '%s')." % text.strip())
    try:
        row, col = int(tokens[0]), int(tokens[1])
    except ValueError:
        raise InvalidMoveError(
            "Row and column must be integers (received: '%s')." % text.strip())
    if not (0 <= row < size and 0 <= col < size):
        raise InvalidMoveError(
            "Move (%d,%d) is out of range - valid rows/cols are 0..%d."
            % (row, col, size - 1))
    return row, col


def load_game_input(path):
    """
    Read inputPS04.txt and return (size, time_limit_ms, cells).

    Format :  line 1  -> N
              line 2  -> time limit in milliseconds
              line 3+ -> the N x N matrix (blank lines and '#' comments ignored)
    An absent matrix is treated as an empty board.
    """
    if not os.path.isfile(path):
        raise InvalidBoardError("Input file '%s' was not found." % path)
    try:
        with open(path, "r", encoding="utf-8") as fh:
            raw = fh.read()
    except OSError as exc:
        raise InvalidBoardError("Cannot read input file '%s' : %s" % (path, exc))

    lines = [ln.strip() for ln in raw.splitlines()]
    lines = [ln for ln in lines if ln and not ln.startswith("#")]
    if len(lines) < 2:
        raise InvalidBoardError(
            "Input file '%s' must contain at least the board size and the "
            "time limit." % path)

    header = []
    for ln in lines[:2]:
        header.extend(t for t in re.split(r"[\s,]+", ln) if t)
    if len(header) != 2:
        raise InvalidBoardError(
            "The first two input lines must contain only the board size and "
            "the time limit.")

    try:
        size = int(header[0])
    except ValueError:
        raise InvalidBoardError("Board size '%s' is not an integer." % header[0])
    if not MIN_BOARD_SIZE <= size <= MAX_BOARD_SIZE:
        raise InvalidBoardError(
            "Board size must satisfy %d <= N <= %d (received: %d)."
            % (MIN_BOARD_SIZE, MAX_BOARD_SIZE, size))

    try:
        time_limit = int(float(header[1]))
    except (ValueError, OverflowError):
        raise InvalidBoardError("Time limit '%s' is not a number." % header[1])
    if time_limit <= 0:
        raise InvalidBoardError(
            "The time limit must be a positive number of milliseconds "
            "(received: %d)." % time_limit)

    body = []
    for ln in lines[2:]:
        row_tokens = [t for t in re.split(r"[\s,]+", ln) if t]
        if len(row_tokens) == 1 and len(row_tokens[0]) == size:
            row_tokens = list(row_tokens[0])
        body.extend(row_tokens)
    expected = size * size
    if not body:
        cells = [EMPTY] * expected
    elif len(body) != expected:
        raise InvalidBoardError(
            "The board matrix holds %d values but %d were expected for a "
            "%dx%d board." % (len(body), expected, size, size))
    else:
        cells = []
        for tok in body:
            try:
                val = int(tok)
            except ValueError:
                raise InvalidBoardError(
                    "Board cell '%s' is not an integer - only 0, 1 and 2 are "
                    "allowed." % tok)
            if val not in (EMPTY, PLAYER_A, PLAYER_B):
                raise InvalidBoardError(
                    "Board cell value %d is invalid - only 0, 1 and 2 are "
                    "allowed." % val)
            cells.append(val)

    a_count, b_count = cells.count(PLAYER_A), cells.count(PLAYER_B)
    if a_count - b_count not in (0, 1):
        raise InvalidBoardError(
            "Inconsistent board: Player A owns %d cells and Player B owns %d. "
            "Player A moves first, so A must own either as many stones as B "
            "or exactly one more." % (a_count, b_count))
    return size, time_limit, cells


