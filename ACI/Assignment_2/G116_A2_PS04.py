class MCTSNode:
    """
    One node of the Monte Carlo search tree.

    `player_just_moved` is the player who created this node's position, so the
    node's win counter is maintained from *that* player's point of view - this
    is what makes the UCT value directly comparable between siblings.
    """

    __slots__ = ("move", "parent", "children", "untried_moves",
                 "visits", "wins", "player_just_moved", "terminal_winner")

    def __init__(self, move, parent, player_just_moved, untried_moves):
        self.move = move
        self.parent = parent
        self.children = []
        self.untried_moves = untried_moves
        self.visits = 0
        self.wins = 0.0
        self.player_just_moved = player_just_moved
        self.terminal_winner = EMPTY      # != 0 -> this position ends the game

    # -- 1. SELECTION ---------------------------------------------------------
    def uct_select_child(self, exploration=EXPLORATION_CONSTANT):
        """Return the child maximising  w/n + c * sqrt(ln(N) / n)."""
        if not self.children:
            raise EmptyTreeError(
                "Selection failed: node has no children to select from.")
        log_parent = math.log(self.visits) if self.visits > 0 else 0.0
        best, best_score = None, -1.0
        for child in self.children:
            score = (child.wins / child.visits
                     + exploration * math.sqrt(log_parent / child.visits))
            if score > best_score:
                best, best_score = child, score
        return best

    # -- 2. EXPANSION ---------------------------------------------------------
    def expand(self, move, player):
        """Attach a new child produced by `player` playing `move`."""
        if self.untried_moves and move in self.untried_moves:
            self.untried_moves.remove(move)
        child = MCTSNode(move, self, player, None)
        self.children.append(child)
        return child

    # -- 4. BACKPROPAGATION ---------------------------------------------------
    def update(self, winner):
        self.visits += 1
        if winner == self.player_just_moved:
            self.wins += 1.0

    @property
    def win_rate(self):
        return self.wins / self.visits if self.visits else 0.0

    def is_fully_expanded(self):
        return not self.untried_moves


class SearchResult:
    """Container for everything the agent has to report about one move."""

    __slots__ = ("move", "row", "col", "win_probability", "simulations",
                 "nodes_expanded", "max_depth", "elapsed_ms", "strategy",
                 "root_visits")

    def __init__(self, move, row, col, win_probability, simulations,
                 nodes_expanded, max_depth, elapsed_ms, strategy, root_visits):
        self.move = move
        self.row = row
        self.col = col
        self.win_probability = win_probability
        self.simulations = simulations
        self.nodes_expanded = nodes_expanded
        self.max_depth = max_depth
        self.elapsed_ms = elapsed_ms
        self.strategy = strategy
        self.root_visits = root_visits


class MCTSAgent:
    """
    The Hex AI agent.

    `choose_move` returns the best legal move found inside the given time
    budget together with the statistics required by the output format.
    """

    def __init__(self, time_limit_ms=DEFAULT_TIME_LIMIT_MS,
                 exploration=EXPLORATION_CONSTANT, seed=None):
        if time_limit_ms <= 0:
            raise HexError("The time limit per move must be a positive number "
                           "of milliseconds (received: %r)." % (time_limit_ms,))
        self.time_limit = time_limit_ms / 1000.0
        self.exploration = exploration
        self.rng = random.Random(seed)

    # ------------------------------------------------------------------ public
    def choose_move(self, board, player):
        start = time.perf_counter()
        legal = board.legal_moves()
        if not legal:
            raise BoardFullError(
                "MCTS cannot search: the board is full and holds no legal move.")

        opponent = 3 - player

        # -- Tactical pre-filter (domain knowledge injected at the root) -------
        # (a) an immediate winning move is played at once - no search needed.
        for mv in legal:
            board.place(mv, player)
            won = board.is_connected(player)
            board.remove(mv)
            if won:
                r, c = board.coords(mv)
                return SearchResult(mv, r, c, 1.0, 0, 0, 0,
                                    (time.perf_counter() - start) * 1000.0,
                                    "MCTS(UCT) + immediate-win detection", 0)

        # (b) if the opponent can win next ply, only blocking moves are kept.
        blocking = []
        for mv in legal:
            board.place(mv, opponent)
            threat = board.is_connected(opponent)
            board.remove(mv)
            if threat:
                blocking.append(mv)
        root_moves = blocking if blocking else legal
        strategy = ("MCTS(UCT) + forced-block filter" if blocking
                    else "Monte Carlo Tree Search (UCT)")

        # -- Full MCTS --------------------------------------------------------
        self.rng.shuffle(root_moves)
        root = MCTSNode(None, None, opponent, list(root_moves))
        simulations = 0
        nodes_expanded = 0
        max_depth = 0
        deadline = start + self.time_limit

        while time.perf_counter() < deadline:
            node = root
            state = board.copy()
            to_move = player
            depth = 0

            # 1. SELECTION -----------------------------------------------------
            while node.is_fully_expanded() and node.children \
                    and node.terminal_winner == EMPTY:
                node = node.uct_select_child(self.exploration)
                state.place(node.move, to_move)
                to_move = 3 - to_move
                depth += 1

            # 2. EXPANSION -----------------------------------------------------
            if node.terminal_winner == EMPTY:
                if node.untried_moves is None:
                    node.untried_moves = state.legal_moves()
                    self.rng.shuffle(node.untried_moves)
                if node.untried_moves:
                    mv = node.untried_moves.pop()
                    state.place(mv, to_move)
                    node = node.expand(mv, to_move)
                    nodes_expanded += 1
                    to_move = 3 - to_move
                    depth += 1
                    if state.is_connected(node.player_just_moved):
                        node.terminal_winner = node.player_just_moved

            if depth > max_depth:
                max_depth = depth

            # 3. SIMULATION (rollout) -----------------------------------------
            if node.terminal_winner != EMPTY:
                winner = node.terminal_winner
            else:
                winner = self._rollout(state, to_move)
            simulations += 1

            # 4. BACKPROPAGATION ----------------------------------------------
            while node is not None:
                node.update(winner)
                node = node.parent

        elapsed_ms = (time.perf_counter() - start) * 1000.0

        # -- Final move choice: the most visited (most robust) child -----------
        if not root.children:
            # Degenerate case (absurdly small time budget): fall back to a
            # random legal move so that the game can always continue.
            mv = self.rng.choice(root_moves)
            r, c = board.coords(mv)
            return SearchResult(mv, r, c, 0.0, simulations, nodes_expanded,
                                max_depth, elapsed_ms,
                                strategy + " [time budget exhausted]", root.visits)

        best = max(root.children, key=lambda ch: (ch.visits, ch.win_rate))
        r, c = board.coords(best.move)
        return SearchResult(best.move, r, c, best.win_rate, simulations,
                            nodes_expanded, max_depth, elapsed_ms, strategy,
                            root.visits)

    # ----------------------------------------------------------------- private
    def _rollout(self, state, to_move):
        """
        Uniformly random play-out.

        Because Hex can never end in a draw, a *completely filled* board always
        contains exactly one winner.  The remaining empty cells can therefore
        be shuffled once and dealt alternately to both players; the resulting
        final position is statistically identical to playing random moves one
        by one, but it removes all per-move bookkeeping and makes the rollout
        an O(N^2) operation.
        """
        cells = state.cells
        empties = [i for i, v in enumerate(cells) if v == EMPTY]
        if not empties:
            return state.winner()
        self.rng.shuffle(empties)
        board_copy = cells[:]
        player = to_move
        for i in empties:
            board_copy[i] = player
            player = 3 - player
        return PLAYER_A if player_a_wins_on_full_board(
            board_copy, state.size, state.neighbours) else PLAYER_B


