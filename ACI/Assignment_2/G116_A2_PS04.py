# ============================================================================
class HexGame:
    """Drives the alternating turns, the logging and the end-of-game report."""

    MAX_INVALID_ATTEMPTS = 10

    def __init__(self, size, time_limit_ms, cells, logger, seed=None):
        self.board = HexBoard(size, cells)
        self.time_limit_ms = time_limit_ms
        self.logger = logger
        self.agent = MCTSAgent(time_limit_ms, seed=seed)
        self.turn = 0
        self.ai_moves = 0
        self.human_moves = 0
        self.ai_times = []
        self.ai_nodes = []
        self.ai_depths = []
        self.ai_sims = []
        self.aborted = False

    # ------------------------------------------------------------------ turns
    def current_player(self):
        """Player A always moves first, so the stone counts fix the turn."""
        return PLAYER_A if self.board.stone_count(PLAYER_A) == \
            self.board.stone_count(PLAYER_B) else PLAYER_B

    def run(self):
        self._log_header()
        winner = self.board.winner()
        if winner:
            self.logger.write("The supplied board is already a terminal state.")
            self._log_game_over(winner)
            return winner

        while True:
            if self.board.is_full():
                break
            self.turn += 1
            player = self.current_player()
            if player == PLAYER_A:
                winner = self._ai_turn()
            else:
                winner = self._human_turn()
                if self.aborted:
                    self._log_game_over(EMPTY)
                    return EMPTY
            if winner:
                self._log_game_over(winner)
                return winner

        winner = self.board.winner()
        self._log_game_over(winner)
        return winner

    def _ai_turn(self):
        result = self.agent.choose_move(self.board, PLAYER_A)
        self.board.place(result.move, PLAYER_A)
        winner = self.board.winner()

        self.ai_moves += 1
        self.ai_times.append(result.elapsed_ms)
        self.ai_nodes.append(result.nodes_expanded)
        self.ai_depths.append(result.max_depth)
        self.ai_sims.append(result.simulations)

        log = self.logger
        log.write("")
        log.write("=" * 20 + "Turn %d" % self.turn + "=" * 31)
        log.write("Player                    : A (AI)")
        log.write("Move Selected             : (%d,%d)" % (result.row, result.col))
        log.write("Search Algorithm          : %s" % result.strategy)
        log.write("Exploration Constant (c)  : %.3f" % self.agent.exploration)
        log.write("Simulations (Rollouts)    : %s" % format_int(result.simulations))
        log.write("Nodes Expanded            : %s" % format_int(result.nodes_expanded))
        log.write("Search Depth (tree)       : %d" % result.max_depth)
        log.write("Heuristic Score (Win Prob): %s"
                  % ("+INF" if winner == PLAYER_A else "%.4f" % result.win_probability))
        log.write("Execution Time            : %d ms" % round(result.elapsed_ms))
        self._log_status(winner)
        return winner

    def _human_turn(self):
        log = self.logger
        size = self.board.size
        attempts = 0
        start = time.perf_counter()
        row = col = idx = None

        log.write("")
        log.write("=" * 20 + "Turn %d" % self.turn + "=" * 31)
        log.write("Player                    : B (Human)")
        log.write("Current Board :")
        log.write(self.board.render())

        while idx is None:
            prompt = "Player B, Enter your move (row,col): "
            try:
                raw = input(prompt)
            except (EOFError, KeyboardInterrupt):
                log.write_prompt(prompt)
                log.write("")
                log.write("No further input available - the game is stopped.")
                self.aborted = True
                return EMPTY
            log.write_prompt(prompt + raw)
            try:
                row, col = parse_move(raw, size)
                idx = self.board.validate_move(row, col)
            except HexError as exc:
                attempts += 1
                log.write("Move Entered              : %s" % raw.strip())
                log.write("Move Validation           : INVALID - %s" % exc)
                if attempts >= self.MAX_INVALID_ATTEMPTS:
                    log.write("Too many invalid moves (%d) - the game is stopped."
                              % attempts)
                    self.aborted = True
                    return EMPTY
                log.write("Please try again.")
                idx = None

        self.board.place(idx, PLAYER_B)
        elapsed_ms = (time.perf_counter() - start) * 1000.0
        winner = self.board.winner()
        self.human_moves += 1

        log.write("Move Entered              : (%d,%d)" % (row, col))
        log.write("Move Validation           : VALID")
        log.write("Invalid Attempts          : %d" % attempts)
        log.write("Execution Time            : %d ms" % round(elapsed_ms))
        self._log_status(winner)
        return winner

    # ---------------------------------------------------------------- logging
    def _log_status(self, winner):
        log = self.logger
        if winner:
            log.write("Game Status               : TERMINAL")
            log.write("Terminal State            : YES")
            log.write("Winner                    : Player %s" % PLAYER_NAME[winner])
            path = self.board.winning_path(winner)
            log.write("Winning Path              : %s"
                      % " -> ".join("(%d,%d)" % rc for rc in path))
        elif self.board.is_full():
            log.write("Game Status               : TERMINAL (board full)")
        else:
            log.write("Game Status               : CONTINUE")
        log.write("Current Board :")
        log.write(self.board.render())

    def _log_header(self):
        log = self.logger
        log.write(SEPARATOR)
        log.write("           HEX GAME AI - MONTE CARLO TREE SEARCH (UCT) - GROUP G116")
        log.write(SEPARATOR)
        log.write("Board Size                : %d x %d" % (self.board.size, self.board.size))
        log.write("Time Limit per AI Move    : %d ms" % self.time_limit_ms)
        log.write("Player A (1)              : AI Agent - connects TOP row to BOTTOM row")
        log.write("Player B (2)              : Human    - connects LEFT col to RIGHT col")
        log.write("Adjacency                 : (r-1,c) (r+1,c) (r,c-1) (r,c+1) "
                  "(r-1,c+1) (r+1,c-1)")
        log.write("Initial Board :")
        log.write(self.board.render())

    def _log_game_over(self, winner):
        log = self.logger
        log.write("")
        log.write(SEPARATOR)
        log.write(" " * 30 + "GAME OVER")
        log.write(SEPARATOR)
        if winner:
            log.write("Winner                    : Player %s" % PLAYER_NAME[winner])
        elif self.aborted:
            log.write("Winner                    : NONE (game aborted by the user)")
        else:
            log.write("Winner                    : NONE")
        log.write("Total Turns               : %d" % self.turn)
        log.write("Total AI Moves            : %d" % self.ai_moves)
        log.write("Total Human Moves         : %d" % self.human_moves)
        if self.ai_moves:
            log.write("Average Simulations       : %s"
                      % format_int(sum(self.ai_sims) / self.ai_moves))
            log.write("Average Nodes Expanded    : %s"
                      % format_int(sum(self.ai_nodes) / self.ai_moves))
            log.write("Average Search Depth      : %.1f"
                      % (sum(self.ai_depths) / self.ai_moves))
            log.write("Average AI Move Time      : %s ms"
                      % format_int(sum(self.ai_times) / self.ai_moves))
            log.write("Maximum Search Depth      : %d" % max(self.ai_depths))
            log.write("Maximum Nodes Expanded    : %s" % format_int(max(self.ai_nodes)))
        if winner == PLAYER_A:
            result = "PLAYER_A_WINS"
        elif winner == PLAYER_B:
            result = "PLAYER_B_WINS"
        else:
            result = "GAME_ABORTED" if self.aborted else "NO_RESULT"
        log.write("Game Result               : %s" % result)
        log.write(SEPARATOR)


