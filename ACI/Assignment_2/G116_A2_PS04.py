# 1. GAME MODEL
# ============================================================================
class HexBoard:
    """
    The Hex board.

    The N x N matrix is stored as a *flat* python list of length N*N so that a
    cell can be addressed by a single integer index (index = row * N + col).
    A flat list makes the millions of read/copy operations performed during the
    MCTS rollouts noticeably cheaper than a list-of-lists.

    The neighbour table is pre-computed once per board size and shared by every
    copy of the board, so adjacency look-up during a rollout costs O(1).
    """

    __slots__ = ("size", "cells", "neighbours")

    def __init__(self, size, cells=None, neighbours=None):
        if not isinstance(size, int) or size < 2:
            raise InvalidBoardError(
                "Board size must be an integer >= 2 (received: %r)." % (size,))
        self.size = size
        if cells is None:
            self.cells = [EMPTY] * (size * size)
        else:
            if len(cells) != size * size:
                raise InvalidBoardError(
                    "Board data holds %d cells but %d were expected for a "
                    "%dx%d board." % (len(cells), size * size, size, size))
            self.cells = list(cells)
        self.neighbours = neighbours if neighbours is not None \
            else self._build_neighbour_table(size)

    # -- construction helpers -------------------------------------------------
    @staticmethod
    def _build_neighbour_table(size):
        """Pre-compute, for every flat index, the tuple of its legal neighbours."""
        table = []
        for r in range(size):
            for c in range(size):
                nb = []
                for dr, dc in NEIGHBOUR_OFFSETS:
                    nr, nc = r + dr, c + dc
                    if 0 <= nr < size and 0 <= nc < size:
                        nb.append(nr * size + nc)
                table.append(tuple(nb))
        return table

    def copy(self):
        """Fast clone - the immutable neighbour table is shared, not copied."""
        return HexBoard(self.size, self.cells, self.neighbours)

    # -- coordinate helpers ---------------------------------------------------
    def index(self, row, col):
        return row * self.size + col

    def coords(self, idx):
        return divmod(idx, self.size)

    def neighbours_of(self, row, col):
        """Public helper returning the (row, col) neighbours of a cell."""
        if not self.in_bounds(row, col):
            raise InvalidMoveError("Cell (%d,%d) is outside the board." % (row, col))
        return [self.coords(i) for i in self.neighbours[self.index(row, col)]]

    def in_bounds(self, row, col):
        return 0 <= row < self.size and 0 <= col < self.size

    # -- insert / delete ------------------------------------------------------
    def legal_moves(self):
        """All empty cells, as flat indices."""
        return [i for i, v in enumerate(self.cells) if v == EMPTY]

    def is_full(self):
        return EMPTY not in self.cells

    def place(self, idx, player):
        """INSERT operation: put `player`'s stone on the empty cell `idx`."""
        if not 0 <= idx < len(self.cells):
            raise InvalidMoveError("Move index %r is outside the board." % (idx,))
        if self.cells[idx] != EMPTY:
            r, c = self.coords(idx)
            raise InvalidMoveError(
                "Cell (%d,%d) is already occupied by Player %s."
                % (r, c, PLAYER_NAME[self.cells[idx]]))
        self.cells[idx] = player

    def remove(self, idx):
        """DELETE operation: undo a stone placement (used by the tactical scan)."""
        if not 0 <= idx < len(self.cells):
            raise InvalidMoveError("Move index %r is outside the board." % (idx,))
        if self.cells[idx] == EMPTY:
            r, c = self.coords(idx)
            raise InvalidMoveError(
                "Cannot remove from cell (%d,%d): the cell is already empty." % (r, c))
        self.cells[idx] = EMPTY

    def validate_move(self, row, col):
        """Validate a human move and return its flat index."""
        if not self.in_bounds(row, col):
            raise InvalidMoveError(
                "Move (%d,%d) is out of range - valid rows/cols are 0..%d."
                % (row, col, self.size - 1))
        idx = self.index(row, col)
        if self.cells[idx] != EMPTY:
            raise InvalidMoveError(
                "Cell (%d,%d) is already occupied by Player %s."
                % (row, col, PLAYER_NAME[self.cells[idx]]))
        if self.is_full():
            raise BoardFullError("The board is full - no further moves are possible.")
        return idx

    # -- terminal test --------------------------------------------------------
    def _edge_cells(self, player):
        """Source cells (start edge) and the goal-edge predicate for `player`."""
        n = self.size
        if player == PLAYER_A:                       # top row -> bottom row
            sources = [c for c in range(n) if self.cells[c] == PLAYER_A]
            goal = lambda i: i >= n * (n - 1)        # noqa: E731
        else:                                        # left col -> right col
            sources = [r * n for r in range(n) if self.cells[r * n] == PLAYER_B]
            goal = lambda i: i % n == n - 1          # noqa: E731
        return sources, goal

    def is_connected(self, player):
        """True when `player` has completed a chain between his two edges."""
        sources, goal = self._edge_cells(player)
        if not sources:
            return False
        seen = bytearray(len(self.cells))
        stack = []
        for i in sources:
            seen[i] = 1
            stack.append(i)
        cells, nbrs = self.cells, self.neighbours
        while stack:
            i = stack.pop()
            if goal(i):
                return True
            for j in nbrs[i]:
                if cells[j] == player and not seen[j]:
                    seen[j] = 1
                    stack.append(j)
        return False

    def winner(self):
        """Return 1 / 2 for a winner, 0 when the game is still running."""
        if self.is_connected(PLAYER_A):
            return PLAYER_A
        if self.is_connected(PLAYER_B):
            return PLAYER_B
        return EMPTY

    def winning_path(self, player):
        """
        Shortest winning chain of `player` as a list of (row, col) tuples.
        Breadth-first search guarantees the shortest connecting path.
        """
        sources, goal = self._edge_cells(player)
        if not sources:
            return []
        parent = {}
        queue = []
        for i in sources:
            parent[i] = None
            queue.append(i)
        cells, nbrs = self.cells, self.neighbours
        head = 0
        while head < len(queue):
            i = queue[head]
            head += 1
            if goal(i):
                path = []
                while i is not None:
                    path.append(self.coords(i))
                    i = parent[i]
                return list(reversed(path))
            for j in nbrs[i]:
                if cells[j] == player and j not in parent:
                    parent[j] = i
                    queue.append(j)
        return []

    # -- presentation ---------------------------------------------------------
    def render(self):
        """Plain matrix rendering, exactly as used by the input file."""
        n = self.size
        return "\n".join(" ".join(str(self.cells[r * n + c]) for c in range(n))
                         for r in range(n))

    def stone_count(self, player):
        return self.cells.count(player)


def player_a_wins_on_full_board(cells, size, neighbours):
    """
    Fast terminal test used by the rollouts.

    A completely filled Hex board always has exactly one winner (no draws), so
    it is enough to test Player A's top-bottom connection: if A is not
    connected then B necessarily is.  Implemented as an iterative depth-first
    flood fill over a bytearray (no recursion, no set hashing) because this is
    the single hottest function of the whole program.
    """
    stack = [c for c in range(size) if cells[c] == PLAYER_A]
    if not stack:
        return False
    seen = bytearray(size * size)
    for i in stack:
        seen[i] = 1
    last_row_start = size * (size - 1)
    while stack:
        i = stack.pop()
        if i >= last_row_start:
            return True
        for j in neighbours[i]:
            if cells[j] == PLAYER_A and not seen[j]:
                seen[j] = 1
                stack.append(j)
    return False


