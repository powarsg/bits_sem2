def run_test_cases(logger):
    logger.write("")
    logger.write(SEPARATOR)
    logger.write(" " * 26 + "BUILT-IN TEST CASES")
    logger.write(SEPARATOR)
    passed = 0
    for title, func in TEST_CASES:
        logger.write("")
        logger.write(title)
        try:
            func(logger)
        except AssertionError as exc:
            logger.write("  RESULT : FAILED - %s" % exc)
        except HexError as exc:
            logger.write("  RESULT : FAILED - unexpected error : %s" % exc)
        else:
            passed += 1
            logger.write("  RESULT : PASSED")
    logger.write("")
    logger.write("%d of %d test cases passed." % (passed, len(TEST_CASES)))
    logger.write(SEPARATOR)
    return passed == len(TEST_CASES)


